"""Password hashing and signed access-token helpers for backend authentication.

Passwords are stored as Argon2 hashes. Verification also accepts the project's
legacy SHA-256 digests so a successful legacy login can transparently upgrade
the stored hash. Access tokens are signed, not encrypted: they contain a user
identifier and must be treated as bearer credentials. Their signature depends
on the server-only ``AUTH_SECRET_KEY`` environment variable.
"""

import hashlib
import hmac
import os

from argon2 import PasswordHasher
from argon2.exceptions import VerifyMismatchError
from itsdangerous import BadSignature, URLSafeTimedSerializer


ACCESS_TOKEN_TTL_SECONDS = 900
REMEMBER_ACCESS_TOKEN_TTL_SECONDS = 7 * 24 * 60 * 60
_ACCESS_TOKEN_SALT = "smartlane-access-token-v1"
_password_hasher = PasswordHasher()


def hash_password(password: str) -> str:
    """Return an Argon2 hash suitable for storing instead of ``password``.

    The plaintext password must not be persisted or logged. A fresh salt is
    generated by the password hasher for each invocation.
    """
    return _password_hasher.hash(password)


def verify_password(password_hash: str, password: str) -> bool:
    """Check a plaintext password against an Argon2 or legacy SHA-256 hash.

    Use constant-time comparison for legacy digests. The caller should only
    issue a token after this returns true and the account is confirmed active.
    """
    if password_hash.startswith("$argon2"):
        try:
            return _password_hasher.verify(password_hash, password)
        except VerifyMismatchError:
            return False

    legacy_hash = hashlib.sha256(password.encode("utf-8")).hexdigest()
    return hmac.compare_digest(password_hash, legacy_hash)


def password_hash_needs_upgrade(password_hash: str) -> bool:
    """Return whether ``password_hash`` is a legacy non-Argon2 digest.

    Upgrade only after the supplied password has been verified successfully.
    """
    return not password_hash.startswith("$argon2")


def _token_serializer() -> URLSafeTimedSerializer:
    """Create the timed-token serializer or fail if its signing key is absent.

    ``AUTH_SECRET_KEY`` must be a strong, private value shared by application
    workers and deployments that need to accept the same tokens.
    """
    secret_key = os.getenv("AUTH_SECRET_KEY")
    if not secret_key:
        raise RuntimeError("AUTH_SECRET_KEY must be configured to use authentication.")

    return URLSafeTimedSerializer(secret_key, salt=_ACCESS_TOKEN_SALT)


def create_access_token(subject: str, remember_me: bool = False) -> str:
    """Issue a signed bearer token whose subject identifies a database user.

    The token is integrity-protected but not encrypted. Do not put passwords,
    roles, or other sensitive claims in its payload; authorization reads the
    user's current role and status from the database. ``remember_me`` selects
    the seven-day token lifetime; otherwise the token is limited to 15 minutes.
    """
    return _token_serializer().dumps({"sub": subject, "remember_me": remember_me})


def get_access_token_subject(token: str) -> str | None:
    """Return a verified, non-empty token subject, or ``None`` if invalid.

    Signature failures and expired tokens are treated as invalid. Remembered
    tokens last at most seven days; ordinary tokens last 15 minutes. Missing
    server configuration raises ``RuntimeError`` rather than making an
    unverifiable token appear valid.
    """
    try:
        serializer = _token_serializer()
        payload = serializer.loads(token, max_age=REMEMBER_ACCESS_TOKEN_TTL_SECONDS)
        if not isinstance(payload, dict) or payload.get("remember_me") is not True:
            payload = serializer.loads(token, max_age=ACCESS_TOKEN_TTL_SECONDS)
    except BadSignature:
        return None

    if not isinstance(payload, dict):
        return None

    subject = payload.get("sub")
    return subject if isinstance(subject, str) and subject else None
